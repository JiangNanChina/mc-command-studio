import { describe, expect, it } from 'vitest'
import {
  createVersionPack,
  assertPackCounts,
  assertPackFileHashes,
  collectPackCounts,
  PACK_FILES,
  parseItemComponents,
  parsePackIndex,
  parsePackManifest,
  pickRegistries
} from './pack'

const manifest = {
  schemaVersion: 1,
  id: '26.3',
  gameVersion: '26.3',
  dataVersion: 5023,
  packFormat: 121,
  type: 'release',
  generatedAt: '2026-01-01T00:00:00.000Z',
  sources: [{ name: 'commands', url: 'https://example.com', sha256: 'a'.repeat(64) }],
  files: PACK_FILES,
  counts: {
    roots: 94,
    literals: 1197,
    parsers: 59,
    items: 1658,
    blocks: 1286,
    enchantments: 43,
    entities: 161
  }
}

describe('version pack', () => {
  it('parses a valid manifest', () => {
    expect(parsePackManifest(manifest).id).toBe('26.3')
    expect(parsePackManifest({ ...manifest, engine: 'nbt' }).engine).toBe('nbt')
  })

  it('parses an alias manifest', () => {
    expect(parsePackManifest({ ...manifest, id: '1.20.6', aliasOf: '1.20.5' }).aliasOf).toBe(
      '1.20.5'
    )
  })

  it('rejects an invalid manifest', () => {
    expect(() => parsePackManifest({ ...manifest, id: '' })).toThrow()
    expect(() => parsePackManifest({ ...manifest, type: 'weekly' })).toThrow()
  })

  it('creates a pack from raw JSON', () => {
    const pack = createVersionPack({
      manifest,
      commands: { type: 'root', children: { give: { type: 'literal' } } },
      registries: { item: ['stone'], block: ['stone'] },
      blocks: { stone: [{}, {}] },
      itemComponents: { stone: {} }
    })
    expect(pack.commands.children?.give.type).toBe('literal')
    expect(pack.registries.item).toEqual(['stone'])
  })

  it('picks only requested registries', () => {
    const picked = pickRegistries({ item: ['a'], block: ['b'], other: ['c'] }, ['item'])
    expect(picked).toEqual({ item: ['a'] })
  })

  it('rejects a commands root with the wrong type', () => {
    expect(() =>
      createVersionPack({
        manifest,
        commands: { type: 'literal', children: {} },
        registries: {},
        blocks: {},
        itemComponents: {}
      })
    ).toThrowError(/root/)
  })

  it('normalizes historical item component arrays without losing values', () => {
    expect(parseItemComponents({ stone: [
      { type: 'minecraft:max_stack_size', value: 64 },
      { type: 'minecraft:enchantments', value: { levels: {} } }
    ] })).toEqual({ stone: {
      'minecraft:max_stack_size': 64,
      'minecraft:enchantments': { levels: {} }
    } })
    expect(() => parseItemComponents({ stone: [
      { type: 'x', value: 1 }, { type: 'x', value: 2 }
    ] })).toThrow(/item-components.json/)
  })

  it('reports file and field names and rejects unsafe manifest paths', () => {
    expect(() => parsePackManifest({ ...manifest, engine: 'invalid' })).toThrow(/manifest.json: engine/)
    expect(() => parsePackManifest({ ...manifest, files: { ...PACK_FILES, commands: '../commands.json' } })).toThrow(/files.commands/)
    expect(() => parsePackManifest({ ...manifest, aliasOf: '..' })).toThrow(/aliasOf/)
    expect(() => parsePackIndex({ schemaVersion: 1, updatedAt: '', packs: [{ id: null }] })).toThrow(/index.json: packs.0.id/)
  })

  it('compares generated bytes with their own hash baseline and requires aliases to match the base', () => {
    const hashes = Object.fromEntries(Object.keys(PACK_FILES).map((key) => [key, 'b'.repeat(64)]))
    const checkedManifest = parsePackManifest({ ...manifest, fileHashes: hashes })
    expect(() => assertPackFileHashes(checkedManifest, hashes)).not.toThrow()
    expect(() => assertPackFileHashes(checkedManifest, { ...hashes, commands: 'c'.repeat(64) })).toThrow(/commands.json: SHA-256/)
    expect(() => assertPackFileHashes(parsePackManifest(manifest), hashes)).toThrow(/缺少 fileHashes/)
    expect(() => assertPackFileHashes(checkedManifest, hashes, { ...checkedManifest, fileHashes: { ...hashes, blocks: 'c'.repeat(64) } })).toThrow(/别名/)
  })

  it('recomputes counts instead of trusting manifest metadata', () => {
    const pack = createVersionPack({
      manifest,
      commands: { type: 'root', children: { give: { type: 'literal', children: { target: { type: 'argument', parser: 'minecraft:entity' } } } } },
      registries: { item: ['stone'], enchantment: ['sharpness'], entity_type: ['pig'] },
      blocks: { stone: [{}, {}] },
      itemComponents: { stone: {} }
    })
    const counts = collectPackCounts(pack)
    expect(counts).toEqual({ roots: 1, literals: 1, parsers: 1, items: 1, blocks: 1, enchantments: 1, entities: 1 })
    expect(() => assertPackCounts(pack)).toThrow(/counts.roots/)
    expect(() => assertPackCounts({ ...pack, manifest: { ...pack.manifest, counts } })).not.toThrow()
  })
})
