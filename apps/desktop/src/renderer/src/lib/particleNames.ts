export function particleName(id: string): string {
  const clean = id.replace(/^minecraft:/, '').split('{')[0]
  return (
    PARTICLE_NAMES[clean] ??
    clean
      .split('_')
      .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
      .join(' ')
  )
}
